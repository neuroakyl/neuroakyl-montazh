#!/usr/bin/env python3
"""Звук эталона словами: какие SFX и музыка, на каком моменте, какого характера. Gemini слушает ТОЛЬКО звук (без картинки),
а моменты берёт из замера razbor12.py — так метка звука совпадает с кадром до сотых.

  python3 -I инструменты/zvuk_etalona.py ПАПКА_ЭТАЛОНА        (нужны original.mp4 и zamer.json) → zvuk.md

Модель: сначала Pro, при лимите — Flash (watch.call перебирает запасные ключи). Claude звук не слышит — это единственный источник
характера звука; время ударов — из замера, не из ответа модели.
"""
import json, pathlib, subprocess, sys, tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import watch  # noqa: E402

MODELS = ["gemini-pro-latest", "gemini-3.8-pro", "gemini-3.5-pro"] + watch.FALLBACK

PROMPT = """Ты саунд-дизайнер коротких вертикальных роликов (Reels/TikTok). Слушай только звук.
Длина ролика {dur:.1f} с. Замер нашёл всплески звука (секунда — сила 0–1):
{udary}

Задача — разложить звуковой монтаж, чтобы его можно было повторить:
1. Музыка: есть ли, жанр/настроение, темп (BPM примерно), громкость относительно голоса (тише на сколько, примерно дБ), где меняется
   (дроп, стоп, приглушение под фразу), где обрывается.
2. Для КАЖДОГО всплеска из списка выше, который не является просто слогом речи: что звучит — вжух (воздух/свист/рывок),
   удар (саб-бас/кино-удар/хлопок), райзер, реверс, щелчок/клик/тап, поп, глитч/помеха, затвор камеры, свайп, «дин»/звон,
   печать клавиатуры, шорох бумаги, мемный звук и т. п. Длина звука, яркость (глухой/звонкий), громкость относительно голоса.
   Формат строки: `секунда — тип — характер — длина — громкость vs голос`.
3. SFX, которых нет в списке, но ты их слышишь — тем же форматом с примерной секундой.
4. Голос: обработка (сухой/с реверберацией, компрессия, есть ли эффект «телефон»/эхо на отдельных словах), паузы вырезаны или живые.
5. Итог 3–5 строками: какой принцип звукового монтажа у этого ролика (сколько SFX в секунду, на что ставят — склейки, появление
   текста, цифры; чего нет — например, нет мемных звуков).
Отвечай по-русски, коротко, только по существу. Не придумывай: не уверен — пиши «неясно»."""


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    d = pathlib.Path(sys.argv[1]).resolve()
    z = json.loads((d / "zamer.json").read_text(encoding="utf-8"))
    ud = [x for x in z["zvuk"] if x[2] >= 0.35]
    udary = "\n".join(f"{t:.2f} — {s:g}" for t, _, s in ud) or "(всплесков нет)"
    with tempfile.TemporaryDirectory() as tmp:
        mp3 = pathlib.Path(tmp) / "zvuk.mp3"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(d / "original.mp4"), "-vn", "-ac", "1", "-b:a", "96k", str(mp3)], check=True)
        prompt = PROMPT.format(dur=z["dur"], udary=udary)
        for m in MODELS:
            try:
                text = watch.call(m, str(mp3), prompt, False)
                (d / "zvuk.md").write_text(f"<!-- Gemini {m}, только звук -->\n# Звук {d.name}\n\n{text}\n", encoding="utf-8")
                print(f"{d.name}: zvuk.md ({m})")
                return
            except Exception as e:  # 404 — нет такой модели, 429 — лимит на всех ключах
                print(f"[{m}] {str(e)[:120]}", file=sys.stderr)
    sys.exit(f"{d.name}: все модели отказали")


if __name__ == "__main__":
    main()
